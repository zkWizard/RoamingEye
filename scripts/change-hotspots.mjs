#!/usr/bin/env node
/**
 * Write public/data/change-hotspots.json.
 *
 * The places are the ones the shipped stories already fly to. Rank is that
 * editorial order, not a measured size of change. This script does not sample
 * imagery, so every row is unverified and carries no headline. A headline is
 * allowed only after someone has checked the place panel's own number and
 * set `verified` plus `headline` on that candidate below.
 *
 * Run: node scripts/change-hotspots.mjs
 */
import { writeFileSync } from "node:fs";

const CANDIDATES = [
  { id: "sahel", title: "Sahel", layerId: "ndvi", lat: 13, lon: 0 },
  { id: "canada", title: "Canada", layerId: "aerosol", lat: 55, lon: -95 },
  { id: "amazon", title: "Amazon", layerId: "aerosol", lat: -10, lon: -60 },
  { id: "sahara", title: "Sahara", layerId: "aerosol", lat: 18, lon: -30 },
  {
    id: "australia",
    title: "Australia",
    layerId: "aerosol",
    lat: -30,
    lon: 150,
  },
  {
    id: "northern-snow",
    title: "The north",
    layerId: "snow",
    lat: 60,
    lon: 40,
  },
];

const hotspots = CANDIDATES.map((place, index) => ({
  ...place,
  sinceYear: 2005,
  headline: null,
  verified: false,
  rank: index + 1,
}));

const file = {
  note: "Generated by scripts/change-hotspots.mjs. verified:false means the headline was not checked against the imagery, and none is published.",
  hotspots,
};

writeFileSync(
  new URL("../public/data/change-hotspots.json", import.meta.url),
  `${JSON.stringify(file, null, 2)}\n`
);
console.log(`wrote ${hotspots.length} hotspots, all unverified`);
